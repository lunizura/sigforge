from __future__ import annotations

from sigforge.models import SigEntry, SigSpec, validate_spec


def _emit_pattern_def(entry: SigEntry) -> str:
    toks = entry.tokens()
    n = len(toks)
    last_locked = 0
    for idx in range(n - 1, -1, -1):
        if toks[idx] is not None:
            last_locked = idx
            break

    bytes_arr = ", ".join(f"0x{(t if t is not None else 0):02X}u" for t in toks)
    mask_arr = ", ".join("0xFFu" if t is not None else "0x00u" for t in toks)
    min_buf_len = max(n, entry.byte_length)

    lines = [
        f"inline constexpr CompiledPattern<{n}> PAT_{entry.name} {{",
        f"    {{{bytes_arr}}},",
        f"    {{{mask_arr}}},",
        f"    {last_locked}u,",
        f"    {min_buf_len}u",
        "};",
        "",
        f"[[nodiscard]] constexpr std::optional<std::size_t> find_{entry.name}(",
        "    std::span<const std::uint8_t> _sf_buf) noexcept {",
        f"    return scan_first(_sf_buf, PAT_{entry.name});",
        "}",
        "",
        f"[[nodiscard]] inline std::optional<std::size_t> find_{entry.name}(",
        "    std::span<const std::byte> _sf_buf) noexcept {",
        f"    return scan_first(as_u8_span(_sf_buf), PAT_{entry.name});",
        "}",
        "",
        f"[[nodiscard]] inline std::vector<std::size_t> find_all_{entry.name}(",
        "    std::span<const std::uint8_t> _sf_buf,",
        "    std::size_t _sf_max_hits = 0) {",
        f"    return scan_all(_sf_buf, PAT_{entry.name}, _sf_max_hits);",
        "}",
        "",
        f"[[nodiscard]] inline std::vector<std::size_t> find_all_{entry.name}(",
        "    std::span<const std::byte> _sf_buf,",
        "    std::size_t _sf_max_hits = 0) {",
        f"    return scan_all(as_u8_span(_sf_buf), PAT_{entry.name}, _sf_max_hits);",
        "}",
    ]

    if entry.rip_capture is not None:
        rc = entry.rip_capture
        lines.extend(
            [
                "",
                f"[[nodiscard]] constexpr std::optional<std::uint64_t> resolve_{entry.name}_rip_target(",
                "    std::span<const std::uint8_t> _sf_buf,",
                "    std::uint64_t _sf_base_rva = 0) noexcept {",
                f"    const auto _sf_hit = find_{entry.name}(_sf_buf);",
                "    if (!_sf_hit.has_value()) {",
                "        return std::nullopt;",
                "    }",
                "    const std::size_t _sf_pos = *_sf_hit;",
                f"    if (_sf_pos + {rc.next_ip_offset}u > _sf_buf.size()) {{",
                "        return std::nullopt;",
                "    }",
                f"    const std::size_t _sf_d = _sf_pos + {rc.disp_offset}u;",
                "    const std::uint32_t _sf_raw =",
                "        static_cast<std::uint32_t>(_sf_buf[_sf_d]) |",
                "        (static_cast<std::uint32_t>(_sf_buf[_sf_d + 1u]) << 8u) |",
                "        (static_cast<std::uint32_t>(_sf_buf[_sf_d + 2u]) << 16u) |",
                "        (static_cast<std::uint32_t>(_sf_buf[_sf_d + 3u]) << 24u);",
                "    const std::int32_t _sf_disp = static_cast<std::int32_t>(_sf_raw);",
                "    const std::uint64_t _sf_ext =",
                "        static_cast<std::uint64_t>(static_cast<std::int64_t>(_sf_disp));",
                "    return _sf_base_rva + static_cast<std::uint64_t>(_sf_pos) +",
                f"           static_cast<std::uint64_t>({rc.next_ip_offset}u) + _sf_ext;",
                "}",
                "",
                f"[[nodiscard]] inline std::optional<std::uint64_t> resolve_{entry.name}_rip_target(",
                "    std::span<const std::byte> _sf_buf,",
                "    std::uint64_t _sf_base_rva = 0) noexcept {",
                f"    return resolve_{entry.name}_rip_target(as_u8_span(_sf_buf), _sf_base_rva);",
                "}",
            ]
        )

    return "\n".join(lines)


